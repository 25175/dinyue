#!/usr/bin/env python3
"""Overlap-fixing mirror of Sukka's reject lists.

Problem: https://ruleset.skk.moe/List/domainset/reject.conf (144k+ ad/tracking
domains) is referenced directly by the Surge profile with a REJECT policy and
pre-matching. Pre-matching REJECT has the highest priority, so any domain in
that list that belongs to an AIGC/DIRECT/Proxy group (e.g. statsig.anthropic.com)
would be DNS-level blocked, and with a DIRECT policy it leaks real IP.

This script mirrors both skk reject lists into this repo, removing every entry
that conflicts with the domain whitelist derived from xiugai.yaml (all rules
whose policy is NOT a REJECT-family policy), and forces no-resolve on IP rules.
The profile then references the mirrors, so upstream list updates can never
swallow our AIGC/DIRECT/Proxy domains again.

Outputs:
  surge/generated/Rules/reject-sink.list         (DOMAIN-SET format)
  surge/generated/Rules/reject-nonip-sink.list   (RULE-SET format)

Run locally: python3 scripts/overlap_fix.py
CI: runs in .github/workflows/sync-surge-family.yml after sync_surge_family.py
"""
from __future__ import annotations

from pathlib import Path
import re
import urllib.request

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'xiugai.yaml'
OUT_DOMAINSET = ROOT / 'surge' / 'generated' / 'Rules' / 'reject-sink.list'
OUT_RULESET = ROOT / 'surge' / 'generated' / 'Rules' / 'reject-nonip-sink.list'

DOMAINSET_URL = 'https://ruleset.skk.moe/List/domainset/reject.conf'
RULESET_URL = 'https://ruleset.skk.moe/List/non_ip/reject.conf'

REJECT_POLICIES = {'REJECT', 'REJECT-DROP', 'REJECT-TINYGIF', 'REJECT-NO-DROP'}
IP_TYPES = {'IP-CIDR', 'IP-CIDR6', 'GEOIP', 'IP-ASN'}
DOMAIN_TYPE_RE = re.compile(r'^[A-Za-z0-9_*-]+(\.[A-Za-z0-9_*-]+)+$')


def load_whitelist():
    data = yaml.safe_load(SOURCE.read_text(encoding='utf-8'))
    suffixes, exacts, keywords = [], [], []
    for item in data.get('rules') or []:
        if not isinstance(item, dict):
            continue
        policy = str(item.get('policy', '')).strip()
        if policy in REJECT_POLICIES:
            continue
        rtype = str(item.get('type', '')).strip().upper()
        value = str(item.get('value', '')).strip().lower()
        if not value:
            continue
        if rtype == 'DOMAIN-SUFFIX':
            suffixes.append(value)
        elif rtype == 'DOMAIN':
            exacts.append(value)
        elif rtype == 'DOMAIN-KEYWORD':
            keywords.append(value)
    return suffixes, exacts, keywords


def conflicts(domain, suffixes, exacts, keywords):
    # Only exact and suffix whitelist entries create real conflicts. Keyword
    # rules are not emitted into the remote split lists used by the profile
    # (generate.py keeps DOMAIN-KEYWORD inline-only), and substring matching on
    # short keywords like 'mt' would nuke ~1000 unrelated ad domains.
    if domain in exacts:
        return True
    for s in suffixes:
        if domain == s or domain.endswith('.' + s):
            return True
    return False


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'overlap_fix/1.0 (+https://github.com/25175/dinyue)'})
    with urllib.request.urlopen(req, timeout=90) as resp:
        return resp.read().decode('utf-8', 'replace')


def mirror_domainset(suffixes, exacts, keywords):
    text = fetch(DOMAINSET_URL)
    kept, dropped = [], []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        domain = stripped.lstrip('.').lower()
        if DOMAIN_TYPE_RE.match(domain) and conflicts(domain, suffixes, exacts, keywords):
            dropped.append(domain)
            continue
        kept.append(stripped)
    header = (
        '# Overlap-fixed mirror of https://ruleset.skk.moe/List/domainset/reject.conf\n'
        f'# Generated by scripts/overlap_fix.py. Conflicts with xiugai.yaml whitelist removed: {len(dropped)}\n'
        f'# Source size: {len(kept) + len(dropped)}, kept: {len(kept)}\n'
    )
    OUT_DOMAINSET.parent.mkdir(parents=True, exist_ok=True)
    OUT_DOMAINSET.write_text(header + '\n'.join(kept) + '\n', encoding='utf-8')
    print(f'domainset: source {len(kept) + len(dropped)}, kept {len(kept)}, dropped {len(dropped)}')
    for d in dropped:
        print(f'  dropped: {d}')
    return dropped


def mirror_ruleset(suffixes, exacts, keywords):
    text = fetch(RULESET_URL)
    kept, dropped = [], []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        parts = [p.strip() for p in stripped.split(',')]
        if len(parts) >= 2 and parts[0] in ('DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD'):
            domain = parts[1].lower()
            if conflicts(domain, suffixes, exacts, keywords):
                dropped.append(stripped)
                continue
        if parts[0] in IP_TYPES and 'no-resolve' not in parts:
            parts.append('no-resolve')
            stripped = ','.join(parts)
        kept.append(stripped)
    header = (
        '# Overlap-fixed mirror of https://ruleset.skk.moe/List/non_ip/reject.conf\n'
        f'# Generated by scripts/overlap_fix.py. IP rules forced no-resolve. Conflicts removed: {len(dropped)}\n'
    )
    OUT_RULESET.write_text(header + '\n'.join(kept) + '\n', encoding='utf-8')
    print(f'ruleset: kept {len(kept)}, dropped {len(dropped)}')
    for d in dropped:
        print(f'  dropped: {d}')
    return dropped


def main():
    suffixes, exacts, keywords = load_whitelist()
    print(f'whitelist: {len(suffixes)} suffixes, {len(exacts)} exact, {len(keywords)} keywords')
    d1 = mirror_domainset(suffixes, exacts, keywords)
    d2 = mirror_ruleset(suffixes, exacts, keywords)
    combined = sorted(set(d1) | {s.split(',', 1)[1].lower() for s in d2})
    print('--- conflict summary (overlap-fixed) ---')
    for d in combined:
        print(f'  {d}')
    if not combined:
        print('  (none)')


if __name__ == '__main__':
    main()
