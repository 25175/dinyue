#!/usr/bin/env python3
"""Mirror and merge per-platform Surge rule lists (X / Reddit / Discord / Meta).

Upstream: blackmatrix7/ios_rule_script, per-platform Surge rule sets
          (rule/Surge/<Platform>/<Platform>.list). The upstream itself already
          aggregates many community rule lists; this script additionally merges
          the Meta-family platforms into one deduplicated rule set.

Upstream license: GPL-2.0-or-later; full text: LICENSES/blackmatrix7-ios_rule_script-GPL-2.0.txt

Why these platforms: the Rabbit-Spec Surge Family upstream has no dedicated
rule sets for X(Twitter), Reddit, Discord or Meta, so their traffic fell
through to the generic Proxy fallback with no policy group of its own.

Outputs:
  surge/上游/blackmatrix7/Rules/<Platform>.list   raw upstream mirrors (backup)
  surge/generated/Rules/X.list                   merged Twitter rules
  surge/generated/Rules/Reddit.list
  surge/generated/Rules/Discord.list
  surge/generated/Rules/Meta.list                merged Facebook+Instagram+Whatsapp+Threads
  surge/generated/Rules/README-...  (no extra file; see surge/generated/README.md)

Run locally: python3 scripts/sync_platform_rules.py
CI check:    python3 scripts/sync_platform_rules.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM_BASE = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Surge"
MIRROR_ROOT = ROOT / "surge" / "上游" / "blackmatrix7" / "Rules"
GENERATED_RULES = ROOT / "surge" / "generated" / "Rules"
LICENSE_NOTICE = "GPL-2.0-or-later; full text: LICENSES/blackmatrix7-ios_rule_script-GPL-2.0.txt"

# Merged platform -> upstream platform lists (in merge order).
PLATFORMS: "OrderedDict[str, list[str]]" = OrderedDict([
    ("X", ["Twitter"]),
    ("Reddit", ["Reddit"]),
    ("Discord", ["Discord"]),
    ("Meta", ["Facebook", "Instagram", "Whatsapp", "Threads"]),
])

# Types legal in a Surge external RULE-SET (matching-condition list, no policy column).
SUPPORTED_TYPES = {
    "DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "DOMAIN-SET",
    "IP-CIDR", "IP-CIDR6", "GEOIP", "IP-ASN",
}


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    raise SystemExit(1)


def fetch_text(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "dinyue-platform-sync/1.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        if response.status != 200:
            fail(f"unexpected upstream HTTP status {response.status}: {url}")
        return response.read().decode("utf-8", "replace")


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def platform_url(platform: str) -> str:
    return f"{UPSTREAM_BASE}/{platform}/{platform}.list"


def parse_rules(text: str, platform: str) -> list[str]:
    """Parse a Surge rule list into normalized 'TYPE,VALUE[,OPTION]' lines."""
    rules: list[str] = []
    for line_number, raw_line in enumerate(text.splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [part.strip() for part in line.split(",")]
        rule_type = parts[0].upper() if parts else ""
        if len(parts) < 2 or len(parts) > 3:
            fail(f"{platform} upstream has malformed rule at line {line_number}: {raw_line}")
        if rule_type not in SUPPORTED_TYPES:
            fail(f"{platform} upstream has unsupported rule type at line {line_number}: {raw_line}")
        if not parts[1]:
            fail(f"{platform} upstream has empty value at line {line_number}: {raw_line}")
        if len(parts) == 3 and not parts[2]:
            fail(f"{platform} upstream has empty option at line {line_number}: {raw_line}")
        rules.append(",".join(parts))
    if not rules:
        fail(f"{platform} upstream returned no supported rules: {platform_url(platform)}")
    return rules


def merge_rules(sources: list[list[str]]) -> list[str]:
    """Dedupe merged rule lines, keeping first occurrence order."""
    merged: list[str] = []
    seen: set[str] = set()
    for source in sources:
        for rule in source:
            if rule not in seen:
                seen.add(rule)
                merged.append(rule)
    return merged


def render_merged(platform: str, parts: list[tuple[str, str, str, list[str]]]) -> str:
    """Build the merged list body. parts: (platform, url, sha256, rules)."""
    total = sum(len(rules) for _, _, _, rules in parts)
    header = [
        f"# Merged Surge RULE-SET for {platform}.",
        "# Generated by scripts/sync_platform_rules.py; do not edit by hand.",
        f"# Upstream license: {LICENSE_NOTICE}",
        "# Sources (raw mirrors under surge/上游/blackmatrix7/Rules/):",
    ]
    for name, url, sha, rules in parts:
        header.append(f"#   - {name}.list: {url} ({len(rules)} rules, sha256={sha[:16]}...)")
    header.append(f"# Merged rules: {total}")
    header.append("")
    merged = merge_rules([rules for _, _, _, rules in parts])
    return "\n".join(header + merged) + "\n"


def sync_platform(platform: str, Upstreams: list[str], check: bool) -> tuple[int, int]:
    """Mirror upstream lists and write (or verify) the merged rule set.

    Returns (merged_rule_count, upstream_rule_total).
    """
    parts: list[tuple[str, str, str, list[str]]] = []
    upstream_total = 0
    for name in Upstreams:
        url = platform_url(name)
        text = fetch_text(url)
        mirror_path = MIRROR_ROOT / f"{name}.list"
        mirror_content = text if text.endswith("\n") else text + "\n"
        if check and not mirror_path.exists():
            fail(f"missing upstream mirror: {mirror_path.relative_to(ROOT)}")
        if check and mirror_path.read_text(encoding="utf-8") != mirror_content:
            fail(f"upstream mirror is stale: {mirror_path.relative_to(ROOT)}; run scripts/sync_platform_rules.py")
        if not check:
            write(mirror_path, mirror_content)
        rules = parse_rules(text, name)
        sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
        parts.append((name, url, sha, rules))
        upstream_total += len(rules)

    merged_content = render_merged(platform, parts)
    merged_path = GENERATED_RULES / f"{platform}.list"
    if check:
        if not merged_path.exists():
            fail(f"missing generated artifact: {merged_path.relative_to(ROOT)}")
        if merged_path.read_text(encoding="utf-8") != merged_content:
            fail(f"generated artifact is stale: {merged_path.relative_to(ROOT)}; run scripts/sync_platform_rules.py")
        action = "verified"
    else:
        write(merged_path, merged_content)
        action = "wrote"
    merged_rules = merge_rules([rules for _, _, _, rules in parts])
    print(
        f"{action} {merged_path.relative_to(ROOT)}: upstream_rules={upstream_total} "
        f"merged_rules={len(merged_rules)} sources={len(parts)}"
    )
    return len(merged_rules), upstream_total


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that every committed artifact matches the current upstream transform",
    )
    args = parser.parse_args()

    total_merged = 0
    total_upstream = 0
    for platform, upstreams in PLATFORMS.items():
        merged, upstream = sync_platform(platform, upstreams, args.check)
        total_merged += merged
        total_upstream += upstream
    print(
        f"platform rules: {len(PLATFORMS)} platforms, "
        f"upstream rules={total_upstream}, merged rules={total_merged}"
    )


if __name__ == "__main__":
    try:
        main()
    except (OSError, UnicodeError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
